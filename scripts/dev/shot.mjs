import { chromium, devices } from 'playwright';
const out = process.argv[2];
const b = await chromium.launch();
const ctx = await b.newContext({ ...devices['iPhone 13'], colorScheme: process.argv[3] || 'light' });
const p = await ctx.newPage();
const errs = [];
p.on('console', m => m.type() === 'error' && errs.push(m.text()));
p.on('pageerror', e => errs.push(String(e)));
await p.goto('http://localhost:5173/memleket');
await p.waitForSelector('path.unit');
await p.waitForTimeout(600);
await p.screenshot({ path: `${out}/m0.png` });
await p.tap('path[data-u="61"]');
await p.waitForTimeout(1200);
console.log(p.url());
await p.screenshot({ path: `${out}/m1.png` });
await p.tap('path[data-u="53"]');
await p.waitForTimeout(1200);
console.log(p.url());
await p.screenshot({ path: `${out}/m2.png` });
await p.goBack(); await p.waitForTimeout(1000); console.log('back', p.url());
await p.goto('http://localhost:5173/cihan'); await p.waitForSelector('path.unit'); await p.waitForTimeout(600);
await p.screenshot({ path: `${out}/c0.png` });
await p.tap('path[data-u="KEN"]'); await p.waitForTimeout(1200); console.log(p.url());
await p.screenshot({ path: `${out}/c1.png` });
console.log('errors', errs);
await b.close();
