import { chromium, devices } from 'playwright';
const out = process.argv[2];
const b = await chromium.launch();
const ctx = await b.newContext({ ...devices['iPhone 13'] });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push(String(e)));
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
const B = 'http://localhost:5173';
await p.goto(B + '/cocuk'); await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/k-home.png` });
await p.goto(B + '/cocuk/yapboz/memleket'); await p.waitForSelector('.kids-piece-wrap'); await p.waitForTimeout(500);
await p.screenshot({ path: `${out}/k-puzzle.png` });
// Parçayı hedefine sürükle: aktif parçanın kutusu ile aynı kimlikteki gölgenin kutusu
const name = await p.locator('.kids-piece-wrap').getAttribute('aria-label');
const piece = await p.locator('.kids-piece.active').boundingBox();
const ghosts = await p.$$eval('.kids-ghost', (els) => els.map((e) => { const r = e.getBoundingClientRect(); return { d: e.getAttribute('d').slice(0, 40), x: r.x + r.width / 2, y: r.y + r.height / 2 }; }));
const pd = (await p.locator('.kids-piece.active').getAttribute('d')).slice(0, 40);
const g = ghosts.find((x) => x.d === pd);
const sx = piece.x + piece.width / 2, sy = piece.y + piece.height / 2;
await p.mouse.move(sx, sy); await p.mouse.down();
for (let i = 1; i <= 15; i++) await p.mouse.move(sx + (g.x - sx) * i / 15, sy + (g.y - sy) * i / 15);
await p.mouse.up(); await p.waitForTimeout(700);
console.log(name, 'yerleşen:', await p.locator('.kids-piece.placed').count(), 'mesaj:', await p.locator('.kids-bubble').textContent());
await p.screenshot({ path: `${out}/k-puzzle2.png` });
await p.goto(B + '/cocuk/kesfet/memleket'); await p.waitForSelector('.kids-pin'); await p.waitForTimeout(800);
await p.locator('.kids-pin').first().tap(); await p.waitForTimeout(1600);
await p.screenshot({ path: `${out}/k-kesfet.png` });
await p.goto(B + '/cocuk/bul/cihan'); await p.waitForSelector('path.unit', { state: 'attached' }); await p.waitForTimeout(1200);
await p.screenshot({ path: `${out}/k-bul.png` });
await p.goto(B + '/cocuk'); await p.getByRole('button', { name: /Büyükler/ }).tap(); await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/k-kilit.png` });
console.log('errors', errs);
await b.close();
