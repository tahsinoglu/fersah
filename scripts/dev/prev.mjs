import { chromium, devices } from 'playwright';
const b = await chromium.launch();
const ctx = await b.newContext({ ...devices['iPhone 13'] });
const p = await ctx.newPage();
const errs = []; p.on('pageerror', e => errs.push(String(e))); p.on('console', m => m.type()==='error' && errs.push(m.text()));
await p.goto('http://localhost:8090/');
await p.waitForSelector('path.unit', { timeout: 10000 });
await p.locator('[data-tab="cihan"]').tap(); await p.waitForSelector('path[data-u="KEN"]', { state: 'attached' });
console.log('cihan ok');
await p.locator('[data-tab="oyna"]').tap(); await p.getByText('Hızlı başla').count();
await p.locator('a[href*="siluet"]').first().tap(); await p.waitForSelector('[data-option]'); console.log('oyun ok');
await p.getByRole('button', { name: 'Oyundan çık' }).tap(); await p.waitForTimeout(500);
await p.locator('[data-tab="oyna"]').tap(); await p.locator('a[href="/cocuk"]').tap(); await p.waitForSelector('.kids-tile'); console.log('çocuk ok');
console.log('errors', errs);
await b.close();
